String _anchor(String id) => id.replaceAll('.', '').toLowerCase();

String _table(Object? schema) {
  final rows = <List<String>>[];
  if (schema is Map<String, Object?>) _rows(schema, '', rows);
  if (rows.isEmpty) return 'None.\n';
  final out = StringBuffer()
    ..writeln('| Name | Type | Required | Notes |')
    ..writeln('|---|---|---|---|');
  for (final r in rows) {
    out.writeln('| ${r.map(_cell).join(' | ')} |');
  }
  return out.toString();
}

void _rows(
  Map<String, Object?> schema,
  String prefix,
  List<List<String>> out, {
  String form = '',
}) {
  final props = (schema['properties'] as Map?)?.cast<String, Object?>() ?? {};
  final required = {...?(schema['required'] as List?)};
  if (props.isEmpty && schema['additionalProperties'] is Map) {
    out.add([
      '`$prefix[key]`',
      _label(schema['additionalProperties']),
      '',
      'Any key.',
    ]);
    return;
  }
  for (final MapEntry(key: name, value: raw) in props.entries) {
    final s = raw is Map<String, Object?> ? raw : const <String, Object?>{};
    final path = '$prefix$name';
    final forms = _forms(s);
    out.add([
      '`$path`',
      forms == null ? _label(s) : 'one of ${forms.length} forms',
      required.contains(name) ? 'yes' : '',
      '$form${_notes(s)}',
    ]);
    final items = s['items'];
    if (forms != null) {
      for (final (i, f) in forms.indexed) {
        _rows(f, '$path.', out, form: 'Form ${i + 1}. ');
      }
    } else if (_hasProps(s)) {
      _rows(s, '$path.', out);
    } else if (s['type'] == 'array' && items is Map<String, Object?>) {
      if (_hasProps(items)) _rows(items, '$path[].', out);
    }
  }
}

/// The variants of an `anyOf` of objects, each listed as its own form.
List<Map<String, Object?>>? _forms(Map<String, Object?> s) {
  final variants = s['anyOf'];
  if (variants is! List ||
      !variants.every((v) => v is Map<String, Object?> && _hasProps(v))) {
    return null;
  }
  return variants.cast<Map<String, Object?>>();
}

bool _hasProps(Map<String, Object?> s) =>
    s['type'] == 'object' && ((s['properties'] as Map?)?.isNotEmpty ?? false);

String _label(Object? s) {
  if (s is Map<String, Object?>) {
    if (_hasProps(s)) return 'object';
    final items = s['items'];
    if (s['type'] == 'array' &&
        items is Map<String, Object?> &&
        _hasProps(items)) {
      return 'object[]';
    }
  }
  return '`${_ts(s, multiline: false)}`';
}

String _notes(Map<String, Object?> s) {
  final parts = [if (s['description'] case final String d) d, ?_constraints(s)];
  return parts.join(' ');
}

String? _constraints(Map<String, Object?> s) {
  String range(Object? min, Object? max, String unit) => switch ((min, max)) {
    (null, null) => '',
    (final a?, null) => 'At least $a$unit.',
    (null, final b?) => 'At most $b$unit.',
    (final a?, final b?) => '$a–$b$unit.',
  };
  final text = [
    range(s['minimum'], s['maximum'], ''),
    range(
      s['minItems'],
      s['maxItems'],
      s['maxItems'] == 1 || s['maxItems'] == null && s['minItems'] == 1
          ? ' item'
          : ' items',
    ),
  ].where((t) => t.isNotEmpty).join(' ');
  return text.isEmpty ? null : text;
}

String _cell(String text) =>
    text.replaceAll('|', r'\|').replaceAll('\n', ' ').trim();

const _apiIntro =
    '''
## The `morkva` object

A module is one classic script. It registers actions at its top level with
`morkva.action(id, handler)`; the runtime then invokes one action per run, in
a fresh sandbox that is thrown away afterwards. Nothing survives between
runs.

| Member | What it does |
|---|---|
| `morkva.action(id, handler)` | Registers an action. Only during the top-level run of the script: later calls are ignored with a warning. `handler(input, ctx)` may return a value or a promise. |
| `morkva.call(op, args?)` | Calls an op (see Operations). Resolves with its result; rejects with a `MorkvaError` whose `code` is one of the error codes. `args` must be a JSON object. |
| `morkva.log(...args)` | A run-log line at level `info`. |
| `morkva.progress({done, total, label?})` | Progress on the pressed button and in the run log. |
| `morkva.version` | The SDK core version, `"$kSdkVersion"`. |

`morkva` is frozen. The only other globals you can rely on are the ES2020
built-ins (`Intl` is **not** guaranteed), `console` (`log`, `info`, `warn`,
`error`, `debug`, all written to the run log) and `setTimeout` /
`clearTimeout`. There is no `setInterval`, no network (`fetch`,
`XMLHttpRequest`, `WebSocket` are gone), no `importScripts`, no `import()`,
no `eval` or `new Function`, and no WebAssembly. Whatever else a given
engine happens to have may be missing on the next one.
''';

const _afterTypes =
    '''
### Return value

- A string becomes the run summary shown in the finish message and the run
  log (cut to 200 characters with "…").
- `{message, ...}`: `message` is the summary; the other keys are kept in the
  run log when they fit in 4 KB. A value over 16 KB keeps only the summary.
- Anything else: the app writes the summary itself ("3 cards updated", "No
  changes").
- A return value that is not JSON, or is over 900 KB, is dropped with a
  warning.

The return value is never written anywhere: changes happen only through
plan ops. Summaries, progress labels and log lines are plain text everywhere.

### Plans

Plan ops (`cards.create`, `cards.update`, `cards.delete`, `fields.*`,
`collections.*` writes, `views.*`) change nothing when called: each adds
items to the run's one plan and resolves with `{status: "planned", planId,
itemCount, summary}`. When the action returns, the runtime seals the plan
and either applies it at once or shows it for review (see the apply policy
in [manifest.md](manifest.md#apply-policy)). So:

- A run's reads do not see its own planned changes.
- Any plan call that fails (other than `no_change`) fails the whole run
  `plan_refused` and nothing is applied, **even if the action caught the
  error**. Check before you plan; `no_change` is safe to catch.
- A run that planned nothing succeeds with "No changes".
- A plan holds at most $kMaxPlanItems items.
- Calls the action did not await still join the plan, as long as they
  finish within 2 s of the action returning.

### Trigger time and execution time

`ctx.card` and `trigger.before` / `trigger.after` are the card as it was
when the trigger fired. Your `morkva.call` reads see the data as it is when
the action runs, which can be later when runs queue up. An update planned on
a stale assumption fails the commit's stale check for that card instead of
overwriting a newer change.

### What fires an event

- Only writes made in this app on this device: changes from other devices or
  the Firebase console fire nothing.
- An offline delete, or a change whose save is confirmed only after the app
  restarts, fires nothing; one confirmed later in the same session fires
  late.
- A calculated value changing because another card changed is not an event.
- Deleting a collection fires no `card.deleted`.
- A failed save fires nothing; undo fires nothing.

### Screen refs

The harness ops accept `@card`, `@selected`, `"from": "@screen"` and
`{"screen": true}` for what is on the user's screen. A module has no screen:
these fail `invalid_args`. Use the ids in `ctx`.
''';

