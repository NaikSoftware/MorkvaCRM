const kDescriptorsPath = 'test/core/harness/goldens/descriptors.json';
const kExamplesDir = 'docs/sdk/examples';
const kExamplesDartPath = 'test/automation/web/sdk_examples.g.dart';

void main(List<String> args) {
  final root = args.isEmpty ? '.' : args.first;
  generateSdkFiles(root).forEach((path, content) {
    File('$root/$path')
      ..createSync(recursive: true)
      ..writeAsStringSync(content);
    stdout.writeln('wrote $path');
  });
}

/// Every generated file under [root], by path relative to it.
Map<String, String> generateSdkFiles(String root) {
  final describe =
      jsonDecode(File('$root/$kDescriptorsPath').readAsStringSync())
          as Map<String, Object?>;
  final ops = moduleCallableOps(describe);
  final errorCodes = [for (final c in describe['errorCodes']! as List) '$c'];
  final examples = _examples(root);
  return {
    'docs/sdk/api.md': _apiMarkdown(describe, ops, errorCodes),
    'docs/sdk/morkva.d.ts': _declarations(describe, ops, errorCodes),
    for (final e in examples)
      '$kExamplesDir/${e.id}/${e.id}.morkva.json': e.bundle,
    kExamplesDartPath: _examplesDart(examples),
  };
}

/// The ops a module may call: read, plan and ui ops whose capability a
/// module can be granted, plus `harness.describe`, minus the namespaces the
/// bridge refuses (`plans`, `journal`, `modules`, `automations`, `runs`).
List<Map<String, Object?>> moduleCallableOps(Map<String, Object?> describe) {
  final grantable = {for (final c in kModuleGrantable) c.wire};
  return [
    for (final op in (describe['ops']! as List).cast<Map<String, Object?>>())
      if (!kDeniedNamespaces.contains('${op['id']}'.split('.').first) &&
          (op['id'] == 'harness.describe' ||
              (const {'read', 'plan', 'ui'}.contains(op['kind']) &&
                  grantable.contains(op['capability']))))
        op,
  ]..sort((a, b) => '${a['id']}'.compareTo('${b['id']}'));
}

