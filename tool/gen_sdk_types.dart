final _identifier = RegExp(r'^[A-Za-z_$][A-Za-z0-9_$]*$');

/// [schema] (the harness JSON Schema subset) as a TypeScript type.
String _ts(Object? schema, {String indent = '', bool multiline = true}) {
  if (schema is! Map<String, Object?>) return 'unknown';
  String inner(Object? s) => _ts(s, indent: '$indent  ', multiline: multiline);
  if (schema['anyOf'] case final List variants) {
    return variants
        .map((v) => _ts(v, indent: indent, multiline: multiline))
        .join(' | ');
  }
  if (schema['enum'] case final List values) {
    return values.map(_literal).join(' | ');
  }
  if (schema.containsKey('const')) return _literal(schema['const']);
  switch (schema['type']) {
    case 'string':
      return 'string';
    case 'number' || 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      final item = _ts(schema['items'], indent: indent, multiline: multiline);
      return item.contains(' | ') ? '($item)[]' : '$item[]';
    case 'object':
      final props =
          (schema['properties'] as Map?)?.cast<String, Object?>() ?? {};
      final extra = schema['additionalProperties'];
      if (props.isEmpty) {
        return extra is Map
            ? '{ [key: string]: ${inner(extra)} }'
            : extra == false
            ? 'Record<string, never>'
            : '{ [key: string]: unknown }';
      }
      final required = {...?(schema['required'] as List?)};
      final members = [
        for (final MapEntry(key: name, value: s) in props.entries)
          (
            doc: s is Map<String, Object?>
                ? [
                    if (s['description'] case final String d) d,
                    ?_constraints(s),
                  ].join(' ')
                : '',
            text:
                '${_identifier.hasMatch(name) ? name : jsonEncode(name)}'
                '${required.contains(name) ? '' : '?'}: ${inner(s)};',
          ),
        if (extra is Map) (doc: '', text: '[key: string]: unknown;'),
      ];
      if (!multiline) {
        return '{ ${members.map((m) => m.text).join(' ')} }';
      }
      final pad = '$indent  ';
      return [
        '{',
        for (final m in members) ...[
          if (m.doc.isNotEmpty) '$pad/** ${_doc(m.doc, '$pad ')} */',
          '$pad${m.text}',
        ],
        '$indent}',
      ].join('\n');
  }
  return 'unknown';
}

String _literal(Object? v) =>
    v is String ? "'${v.replaceAll("'", r"\'")}'" : jsonEncode(v);

/// [text] safe inside a `/** */` comment.
String _doc(String text, String pad) =>
    text.replaceAll('*/', '*\\/').replaceAll('\n', '\n$pad* ');
