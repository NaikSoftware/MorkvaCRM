typedef _Example = ({String id, String bundle});

List<_Example> _examples(String root) {
  final dirs =
      Directory(
          '$root/$kExamplesDir',
        ).listSync().whereType<Directory>().toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  return [for (final dir in dirs) _example(dir)];
}

_Example _example(Directory dir) {
  final id = dir.uri.pathSegments.where((s) => s.isNotEmpty).last;
  final manifest =
      jsonDecode(File('${dir.path}/manifest.json').readAsStringSync())
          as Map<String, Object?>;
  final code = File('${dir.path}/module.js').readAsStringSync();
  // Throws ManifestProblems for a manifest the app would refuse.
  final bundle = ModuleBundle.of(manifest, code);
  if (bundle.manifest.id != id) {
    throw StateError('$dir: the manifest id is "${bundle.manifest.id}"');
  }
  // What the README's node snippet writes: JSON.stringify(…, null, 2).
  return (id: id, bundle: bundle.encode());
}

String _examplesDart(List<_Example> examples) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_sdk_types.dart from docs/sdk/examples.')
    ..writeln('// Do not edit: run `dart run tool/gen_sdk_types.dart`.')
    ..writeln()
    ..writeln('/// Example id → its `*.morkva.json` file text.')
    ..writeln('const Map<String, String> kSdkExamples = {');
  for (final e in examples) {
    if (e.bundle.contains("'''")) {
      throw StateError("${e.id}: the bundle may not contain '''");
    }
    out
      ..writeln("  '${e.id}': r'''")
      ..writeln("${e.bundle}''',");
  }
  out.writeln('};');
  return out.toString();
}

